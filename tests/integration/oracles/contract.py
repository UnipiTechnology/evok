"""The contract of the API: the OpenAPI document of Evok.

Every device state in a response and every body of a write is validated against the
schemas of the OpenAPI document, the definition of the API generated from the sources
of Evok. The harness does not import Evok: the document is generated by a subprocess
of the Evok project (``python -m evok.openapi``), or read from ``EVOK_OPENAPI``, e.g.
the document attached to a release, to check a device with another version.

The device type of a schema is the ``dev`` of its examples; the params of a POST are
the request body of the path of the device type.
"""

import os
import subprocess
import tempfile
from functools import cache
from pathlib import Path

import yaml
from jsonschema import Draft202012Validator

REPO_ROOT = Path(__file__).resolve().parents[3]


@cache
def document() -> dict:
    """The OpenAPI document of the tested Evok"""
    path = os.environ.get("EVOK_OPENAPI")
    if path:
        return yaml.safe_load(Path(path).read_text())
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "Evok_API_OAS.yaml"
        # the project of Evok, not the environment of the harness
        env = {k: v for k, v in os.environ.items() if k != "VIRTUAL_ENV"}
        subprocess.run(
            ["uv", "run", "--quiet", "python", "-m", "evok.openapi", "-o", str(out)],
            cwd=REPO_ROOT,
            env=env,
            check=True,
            capture_output=True,
        )
        return yaml.safe_load(out.read_text())


def _schemas() -> dict:
    return document()["components"]["schemas"]


@cache
def _state_components() -> dict[str, str]:
    """The component of the state of each device type, by the `dev` of its examples"""
    by_dev: dict[str, str] = {}
    for name, schema in _schemas().items():
        for example in schema.get("examples", []):
            if isinstance(example, dict) and "dev" in example and "circuit" in example:
                by_dev.setdefault(example["dev"], name)
    return by_dev


@cache
def _params_components() -> dict[str, str]:
    """The component of the params of a POST, by the segment of the path and by the dev"""
    by_key: dict[str, str] = {}
    for path, item in document()["paths"].items():
        parts = path.strip("/").split("/")
        if (
            len(parts) != 3
            or parts[0] != "{format}"
            or parts[2] != "{circuit}"
            or "post" not in item
        ):
            continue
        content = item["post"]["requestBody"]["content"]
        params = next(iter(content.values()))["schema"]["$ref"].rsplit("/", 1)[-1]
        by_key[parts[1]] = params
        # the devs of the states of the path, e.g. 1wdevice of the path temp
        state = item.get("get", {}).get("responses", {}).get("200", {})
        text = yaml.safe_dump(state)
        for dev, component in _state_components().items():
            if f"#/components/schemas/{component}'" in text:
                by_key.setdefault(dev, params)
    return by_key


@cache
def _validator(component: str) -> Draft202012Validator:
    return Draft202012Validator(_schemas()[component])


def state_schema(dev: str) -> dict | None:
    component = _state_components().get(dev)
    return None if component is None else _schemas()[component]


def validate_response(payload: dict) -> list[str]:
    """The errors of a device state by the schema of its device type"""
    dev = payload.get("dev")
    component = _state_components().get(dev)
    if component is None:
        return [f"device type {dev!r} is not in the definition of the API"]
    return sorted(e.message for e in _validator(component).iter_errors(payload))


def validate_input(key: str, body: dict) -> list[str]:
    """The errors of the params of a POST by the segment of the path or by the dev of the device"""
    component = _params_components().get(key)
    if component is None:
        return []
    return sorted(e.message for e in _validator(component).iter_errors(body))


def device_types() -> set[str]:
    return set(_state_components())
